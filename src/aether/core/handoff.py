"""Handoff manager — validate, persist, synthesize."""

from __future__ import annotations

from typing import Optional

from aether.adapters.base import BaseAdapter
from aether.domain.enums import HandoffStatus
from aether.domain.models import HandoffReport, TaskMemory
from aether.storage.repository import SqliteRepository


class HandoffManager:
    def __init__(self, repo: SqliteRepository) -> None:
        self.repo = repo

    def validate(self, handoff: HandoffReport) -> tuple[bool, list[str]]:
        errors: list[str] = []
        if not handoff.task_id:
            errors.append("missing task_id")
        if not handoff.from_agent:
            errors.append("missing from_agent")
        if handoff.status == HandoffStatus.PARTIAL and not handoff.remaining:
            errors.append("PARTIAL requires remaining work")
        if handoff.status == HandoffStatus.FAILED and not handoff.known_bugs:
            errors.append("FAILED should include known_bugs")
        if not handoff.recommended_next_action and handoff.status != HandoffStatus.COMPLETE:
            errors.append("missing recommended_next_action")
        return (len(errors) == 0, errors)

    async def accept(
        self,
        handoff: HandoffReport,
        synthesize_if_invalid: bool = True,
    ) -> HandoffReport:
        ok, errors = self.validate(handoff)
        if not ok and synthesize_if_invalid:
            handoff.known_bugs = list(handoff.known_bugs) + ["malformed_handoff:" + ",".join(errors)]
            if not handoff.remaining:
                handoff.remaining = [handoff.recommended_next_action or "continue task"]
            if not handoff.recommended_next_action:
                handoff.recommended_next_action = handoff.remaining[0]
            if handoff.status == HandoffStatus.COMPLETE and errors:
                handoff.status = HandoffStatus.PARTIAL
        await self.repo.save_handoff(handoff)
        return handoff

    def synthesize(
        self,
        task_id: str,
        from_agent: str,
        requested: str,
        output: str = "",
        error: str = "",
        memory: Optional[TaskMemory] = None,
    ) -> HandoffReport:
        if output.strip():
            return BaseAdapter.parse_handoff(task_id, from_agent, output, requested=requested)
        remaining = []
        if memory and memory.next_action:
            remaining.append(memory.next_action)
        elif requested:
            remaining.append(requested)
        else:
            remaining.append("continue task from last checkpoint")
        return HandoffReport(
            task_id=task_id,
            from_agent=from_agent,
            status=HandoffStatus.FAILED if error else HandoffStatus.PARTIAL,
            requested=requested,
            completed=["partial execution captured by orchestrator"] if not error else [],
            remaining=remaining,
            known_bugs=[error] if error else ["incomplete_execution"],
            assumptions=["Synthetic handoff generated by orchestrator"],
            recommended_next_action=remaining[0],
        )

    async def apply_to_memory(self, memory: TaskMemory, handoff: HandoffReport) -> TaskMemory:
        memory.last_agent = handoff.from_agent
        memory.last_action = "; ".join(handoff.completed) if handoff.completed else memory.last_action
        memory.next_action = handoff.recommended_next_action or memory.next_action
        for d in handoff.decisions:
            from aether.domain.models import Decision

            memory.decisions.append(Decision(text=d, made_by=handoff.from_agent))
        for bug in handoff.known_bugs:
            if bug and bug not in memory.known_issues:
                memory.known_issues.append(bug)
        for f in handoff.files_changed:
            if f not in memory.files_index:
                memory.files_index.append(f)
        if handoff.status == HandoffStatus.COMPLETE and not handoff.remaining:
            memory.current_state = f"Agent {handoff.from_agent} completed assigned work."
        else:
            memory.current_state = (
                f"Agent {handoff.from_agent} handoff {handoff.status.value}. "
                f"Remaining: {', '.join(handoff.remaining[:5])}"
            )
        await self.repo.save_memory(memory)
        return memory
